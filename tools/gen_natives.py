#!/usr/bin/env python3
"""Generate shared/include/rdr2/natives.h from data/natives.json.

data/natives.json comes from https://github.com/alloc8or/rdr3-nativedb-data
(the data behind https://alloc8or.re/rdr3/nativedb/).

Usage:
    python tools/gen_natives.py            regenerate natives.h
    python tools/gen_natives.py --check    exit 1 if natives.h is out of date
    python tools/gen_natives.py --update   download the latest natives.json, then regenerate
"""

import argparse
import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JSON_PATH = ROOT / "data" / "natives.json"
HEADER_PATH = ROOT / "shared" / "include" / "rdr2" / "natives.h"
SOURCE_URL = "https://raw.githubusercontent.com/alloc8or/rdr3-nativedb-data/master/natives.json"

# Parameter names that would collide with C++ keywords or with macros from <windows.h>.
RESERVED = {
    "alignas", "alignof", "and", "and_eq", "asm", "auto", "bitand", "bitor", "bool", "break",
    "case", "catch", "char", "char8_t", "char16_t", "char32_t", "class", "compl", "concept",
    "const", "consteval", "constexpr", "constinit", "const_cast", "continue", "co_await",
    "co_return", "co_yield", "decltype", "default", "delete", "do", "double", "dynamic_cast",
    "else", "enum", "explicit", "export", "extern", "false", "float", "for", "friend", "goto",
    "if", "inline", "int", "long", "mutable", "namespace", "new", "noexcept", "not", "not_eq",
    "nullptr", "operator", "or", "or_eq", "private", "protected", "public", "register",
    "reinterpret_cast", "requires", "return", "short", "signed", "sizeof", "static",
    "static_assert", "static_cast", "struct", "switch", "template", "this", "thread_local",
    "throw", "true", "try", "typedef", "typeid", "typename", "union", "unsigned", "using",
    "virtual", "void", "volatile", "wchar_t", "while", "xor", "xor_eq",
    # <windows.h> macros
    "near", "far", "small", "min", "max", "interface", "pascal", "cdecl", "IN", "OUT",
    "OPTIONAL", "CONST", "VOID", "TRUE", "FALSE", "NULL", "ERROR", "DELETE", "IGNORE",
}


def clean_comment(text):
    lines = []
    for line in text.replace("\r", "").split("\n"):
        line = "".join(ch for ch in line if ch == "\t" or ch >= " ")
        # A trailing backslash would splice the next source line into this // comment.
        line = line.rstrip().rstrip("\\").rstrip()
        lines.append(line)
    while lines and not lines[-1]:
        lines.pop()
    return lines


def param_list(params):
    """Return (C++ parameter declarations, argument names, is_variadic)."""
    decls, names, seen = [], [], set()
    variadic = False
    for i, p in enumerate(params):
        if p["name"] == "...":
            variadic = True
            continue
        name = p["name"] or f"p{i}"
        if name in RESERVED:
            name += "_"
        while name in seen:
            name += "_"
        seen.add(name)
        decls.append(f"{p['type']} {name}")
        names.append(name)
    return decls, names, variadic


def generate(natives, source_note):
    out = [
        "// AUTO-GENERATED by tools/gen_natives.py from data/natives.json. Do not edit by hand:",
        "// change the generator or update the JSON, then run `python tools/gen_natives.py`.",
        f"// Native data: {source_note}",
        "#pragma once",
        "",
        '#include "invoke.h"',
        "",
        "// clang-format off",
    ]
    for ns, entries in natives.items():
        out.append("")
        out.append(f"namespace {ns} {{")
        for hash_, n in entries.items():
            decls, names, variadic = param_list(n["params"])
            ret = n["return_type"]
            for line in clean_comment(n["comment"]):
                out.append(f"// {line}".rstrip())
            if n.get("unused"):
                out.append("// [Unused by the game's own scripts; may not work.]")
            args = "".join(f", {a}" for a in names)
            if variadic:
                decls.append("Args... args")
                args += ", args..."
                out.append("template <typename... Args>")
            body = f"invoke<{ret}>({hash_}{args});"
            if ret != "void":
                body = "return " + body
            out.append(f"inline {ret} {n['name']}({', '.join(decls)}) {{ {body} }}")
        out.append(f"}} // namespace {ns}")
    out.append("")
    out.append("// clang-format on")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if natives.h is out of date")
    ap.add_argument("--update", action="store_true", help="download the latest natives.json first")
    args = ap.parse_args()

    if args.update:
        print(f"Downloading {SOURCE_URL}")
        with urllib.request.urlopen(SOURCE_URL, timeout=60) as resp:
            data = resp.read()
        json.loads(data)  # refuse to save something that isn't JSON
        JSON_PATH.write_bytes(data)

    natives = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    count = sum(len(v) for v in natives.values())
    header = generate(natives, "alloc8or/rdr3-nativedb-data (" + str(count) + " natives)")

    if args.check:
        current = HEADER_PATH.read_text(encoding="utf-8") if HEADER_PATH.exists() else ""
        if current != header:
            print("natives.h is out of date: run `python tools/gen_natives.py`", file=sys.stderr)
            return 1
        print("natives.h is up to date")
        return 0

    with open(HEADER_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write(header)
    print(f"Wrote {HEADER_PATH.relative_to(ROOT)} ({count} natives)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
